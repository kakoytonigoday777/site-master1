@app.get("/nature/{species_name}", response_class=HTMLResponse)
async def species_page(request: Request, species_name: str):
    # Ищем картинку в наших списках
    image_url = None
    for group in PLANTS["groups"]:
        for item in group["items"]:
            if item["name"].lower() == species_name.lower() and item["image"]:
                image_url = item["image"]
                break

    if not image_url:
        for group in ANIMALS["mammals"] + ANIMALS["birds"]:
            for item in group["items"]:
                if item["name"].lower() == species_name.lower() and item["image"]:
                    image_url = item["image"]
                    break

    # Ищем текст. Если текста нет, выводим заглушку.
    description = SPECIES_DETAILS.get(species_name.lower())
    if not description:
        description = DEFAULT_DESCRIPTION.format(species_name.capitalize())

    return templates.TemplateResponse(
        "species.html",
        {
            "request": request,
            "title": species_name.capitalize(),
            "image": image_url,
            "description": description
        }
    )


